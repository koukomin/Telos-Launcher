def esc(s):
    s = s.replace('&', '&amp;') if '<' not in s else s
    if '<' not in s:
        s = s.replace('<', '&lt;').replace('>', '&gt;')
    s = s.replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')
    if s.startswith('@') or s.startswith('?'):
        s = '\\' + s
    return s

def main():
    values_dirs = sorted([d for d in glob.glob(os.path.join(RES, 'values-*')) if not ('feminine' in d or 'masculine' in d or 'en-r' in d)])

    updated_locales = 0
    added_strings_count = 0

    for vdir in values_dirs:
        loc = os.path.basename(vdir).replace('values-', '')
        target_xml = os.path.join(vdir, 'strings_telos_translations.xml')

        # Load existing names
        existing_names = set()
        if os.path.exists(target_xml):
            try:
                tree = ET.parse(target_xml)
                existing_names = {e.attrib.get('name') for e in tree.getroot().findall('string')}
            except Exception:
                pass

        items_to_add = []
        for key, lang_map in TRANSLATIONS.items():
            if loc in lang_map and key not in existing_names:
                val = lang_map[loc]
                items_to_add.append((key, val))

        if not items_to_add:
            continue

        lines = []
        if os.path.exists(target_xml):
            with open(target_xml, 'r', encoding='utf-8') as f:
                content = f.read().strip()
            if content.endswith('</resources>'):
                content = content[:-12].rstrip()
                lines = [content]
            else:
                lines = ["<?xml version='1.0' encoding='utf-8'?>\n<resources>"]
        else:
            lines = ["<?xml version='1.0' encoding='utf-8'?>\n<resources>"]

        for k, v in items_to_add:
            lines.append(f'    <string name="{k}">{esc(v)}</string>')
            added_strings_count += 1

        lines.append('</resources>\n')

        with open(target_xml, 'w', encoding='utf-8') as f:
            f.write('\n'.join(lines))

        updated_locales += 1
        print(f'Updated {loc} with {len(items_to_add)} new strings.')

    print(f'Done! Updated {updated_locales} locale folders with a total of {added_strings_count} translations.')

if __name__ == '__main__':
    main()
